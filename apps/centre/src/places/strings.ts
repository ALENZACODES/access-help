export type PlacesKey = keyof typeof PLACES_STRINGS.en;

export function placesText(language: "en" | "fr", key: PlacesKey, vars: Record<string, string | number> = {}): string {
  const template: string = PLACES_STRINGS[language][key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function missingPlacesKeys(): string[] {
  return (Object.keys(PLACES_STRINGS.en) as PlacesKey[]).filter(
    (key) => !(key in PLACES_STRINGS.fr) || PLACES_STRINGS.fr[key].trim() === "",
  );
}
