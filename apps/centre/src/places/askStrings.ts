export type AskKey = keyof (typeof ASK_STRINGS)["en"];

export function askText(language: "en" | "fr", key: AskKey, vars: Record<string, string | number> = {}): string {
  const template: string = ASK_STRINGS[language][key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function missingAskKeys(): string[] {
  return (Object.keys(ASK_STRINGS.en) as AskKey[]).filter((key) => !(key in ASK_STRINGS.fr) || ASK_STRINGS.fr[key].trim() === "");
}
