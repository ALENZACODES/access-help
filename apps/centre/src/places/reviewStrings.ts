export type ReviewKey = keyof (typeof REVIEW_STRINGS)["en"];

export function reviewText(language: "en" | "fr", key: ReviewKey, vars: Record<string, string | number> = {}): string {
  const template: string = REVIEW_STRINGS[language][key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function missingReviewKeys(): string[] {
  return (Object.keys(REVIEW_STRINGS.en) as ReviewKey[]).filter(
    (key) => !(key in REVIEW_STRINGS.fr) || REVIEW_STRINGS.fr[key].trim() === "",
  );
}
