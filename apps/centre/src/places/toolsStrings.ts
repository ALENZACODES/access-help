export type ToolsKey = keyof typeof TOOLS_STRINGS.en;

export function toolsText(language: "en" | "fr", key: ToolsKey, vars: Record<string, string | number> = {}): string {
  const template: string = TOOLS_STRINGS[language][key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}
