export type MatchKey = keyof (typeof MATCH_STRINGS)["en"];

export function matchPageText(language: "en" | "fr", key: MatchKey, vars: Record<string, string | number> = {}): string {
  const template: string = MATCH_STRINGS[language][key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function missingMatchKeys(): string[] {
  return (Object.keys(MATCH_STRINGS.en) as MatchKey[]).filter((key) => !(key in MATCH_STRINGS.fr) || MATCH_STRINGS.fr[key].trim() === "");
}
