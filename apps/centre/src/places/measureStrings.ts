export type MeasureKey = keyof (typeof MEASURE_STRINGS)["en"];

export function measureText(language: "en" | "fr", key: MeasureKey, vars: Record<string, string | number> = {}): string {
  const template: string = MEASURE_STRINGS[language][key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function missingMeasureKeys(): string[] {
  return (Object.keys(MEASURE_STRINGS.en) as MeasureKey[]).filter((key) => !(key in MEASURE_STRINGS.fr) || MEASURE_STRINGS.fr[key].trim() === "");
}
