export type MoreKey = keyof typeof MORE_STRINGS.en;

export function moreText(language: "en" | "fr", key: MoreKey, vars: Record<string, string | number> = {}): string {
  const template: string = MORE_STRINGS[language][key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

