export type DayKey = keyof (typeof DAY_STRINGS)["en"];

export function dayText(language: "en" | "fr", key: DayKey, vars: Record<string, string | number> = {}): string {
  let text: string = DAY_STRINGS[language][key];
  for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
  return text;
}
