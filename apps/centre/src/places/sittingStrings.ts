export type SittingKey = keyof (typeof SITTING_STRINGS)["en"];

export function sittingStringText(language: "en" | "fr", key: SittingKey, vars: Record<string, string | number> = {}): string {
  const template: string = SITTING_STRINGS[language][key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function missingSittingKeys(): string[] {
  return (Object.keys(SITTING_STRINGS.en) as SittingKey[]).filter((key) => !(key in SITTING_STRINGS.fr) || SITTING_STRINGS.fr[key].trim() === "");
}
