export type LicencesKey = keyof (typeof LICENCES_STRINGS)["en"];

export function licencesText(language: "en" | "fr", key: LicencesKey, vars: Record<string, string | number> = {}): string {
  const template: string = LICENCES_STRINGS[language][key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function missingLicencesKeys(): string[] {
  return (Object.keys(LICENCES_STRINGS.en) as LicencesKey[]).filter((key) => !(key in LICENCES_STRINGS.fr) || LICENCES_STRINGS.fr[key].trim() === "");
}
