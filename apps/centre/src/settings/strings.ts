export type SettingsKey = keyof typeof SETTINGS_STRINGS.en;

export function settingsText(language: "en" | "fr", key: SettingsKey, vars: Record<string, string | number> = {}): string {
  const template: string = SETTINGS_STRINGS[language][key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function missingSettingsKeys(): string[] {
  return (Object.keys(SETTINGS_STRINGS.en) as SettingsKey[]).filter(
    (key) => !(key in SETTINGS_STRINGS.fr) || SETTINGS_STRINGS.fr[key].trim() === "",
  );
}
